#!/usr/bin/env python3
"""Regenerate the publication sections in docs/ from data/publications/*.toml.

Run with Python 3.11 or newer. Edit the HTML outside the marked sections to
change a profile biography or page layout. Only numbered archive pages are
fully generated.
"""

from __future__ import annotations

import json
import math
import re
import tomllib
import unicodedata
from datetime import date
from html import escape
from pathlib import Path
from tempfile import NamedTemporaryFile
from urllib.parse import urlsplit

from paths import localize


ROOT = Path(__file__).resolve().parents[1]
PUBLICATIONS = "<!-- publications:start -->", "<!-- publications:end -->"
HIGHLIGHTS = "<!-- highlights:start -->", "<!-- highlights:end -->"
PAGE_COUNT = re.compile(r'\s*<meta name="mlps-publication-pages" content="\d+">')
GENERATED = "<!-- Generated by scripts/publications.py -->"


def html(value: object) -> str:
    return escape(str(value), quote=True)


def marked_section(document: str, markers: tuple[str, str], content: str) -> str:
    start, end = markers
    if document.count(start) != 1 or document.count(end) != 1:
        raise ValueError(f"Expected one pair of markers {start} and {end}")
    before, rest = document.split(start)
    _, after = rest.split(end)
    return f"{before}{start}\n{content}\n{end}{after}"


def image_tag(image: dict, route: str, *, eager: bool = False) -> str:
    src = image["src"]
    attrs = {
        "src": localize(src, route),
        "alt": image.get("alt", ""),
        "decoding": "async",
        "loading": "eager" if eager else "lazy",
    }
    for key in ("width", "height", "class"):
        if image.get(key):
            attrs[key] = image[key]
    if eager:
        attrs["fetchpriority"] = "high"
    # Responsive candidates are optional. Keep absence distinct from an empty
    # src attribute, which some browsers interpret as the current document.
    sizes = image.get("sources", {})
    if sizes:
        sources = {width: localize(url, route) for width, url in sizes.items()}
        available = {width: url for width, url in sources.items() if not urlsplit(url).netloc}
        if available and urlsplit(attrs["src"]).netloc:
            attrs["src"] = next(iter(available.values()))
        attrs["srcset"] = ", ".join(f"{url} {width}" for width, url in (available or sources).items())
        if image.get("sizes"):
            attrs["sizes"] = image["sizes"]
    return "<img " + " ".join(f'{key}="{html(value)}"' for key, value in attrs.items()) + ">"


def card(paper: dict, route: str) -> str:
    title = html(paper["title"])
    target = paper.get("pdf_url") or paper.get("detail_url") or paper.get("links", {}).get("Website")
    if target:
        title = f'<a href="{html(localize(target, route))}">{title}</a>'
    output = ['<article class="publication-card">']
    if paper.get("image"):
        output.append(f'  <div class="publication-image">{image_tag(paper["image"], route)}</div>')
    output.extend([
        '  <div class="publication-content">',
        f'    <h3 class="publication-title">{title}</h3>',
    ])
    if paper.get("authors"):
        output.append(f'    <div class="publication-authors">{html(", ".join(paper["authors"]))}</div>')
    meta = [paper.get("venue"), paper["date"][:4]]
    output.append('    <div class="publication-meta">' + "".join(f"<span>{html(v)}</span>" for v in meta if v)
                  + "</div>")
    if paper.get("abstract"):
        paragraphs = "".join("<p>" + html(p.strip()).replace("\n", "<br>\n") + "</p>"
                             for p in re.split(r"\n\s*\n", paper["abstract"].strip()))
        output.append(f'    <div class="publication-description">{paragraphs}</div>')
    output.append('    <div class="publication-links">')
    links = paper.get("links", {})
    ordering = list(links)
    if paper.get("bibtex"):
        ordering.insert(1 if "Website" in links else 0, "BibTeX")
    for label in ordering:
        if label == "BibTeX":
            output.append('      <textarea class="publication-bibtex-source" hidden>'
                          + html(paper["bibtex"].strip()) + "</textarea>")
            output.append('      <button type="button" class="publication-link publication-bibtex-button">BibTeX</button>')
        else:
            href = html(localize(links[label], route))
            output.append(f'      <a class="publication-link" href="{href}" target="_blank" rel="noopener">{html(label)}</a>')
    output.extend(["    </div>", "  </div>", "</article>"])
    return "\n".join(output)


def highlights(papers: list[dict], route: str) -> str:
    selected = sorted((paper for paper in papers if "highlight" in paper),
                      key=lambda paper: paper["highlight"]["position"])
    figures = []
    for rank, paper in enumerate(selected):
        feature = paper["highlight"]
        suffix = f' ({feature["citation"]})' if feature.get("citation") else ""
        caption = feature.get("caption") or paper["title"] + suffix
        img = image_tag(feature.get("image") or paper["image"], route, eager=rank == 0)
        figures.append(f'<figure class="wp-block-image size-full">{img}'
                       f'<figcaption class="wp-element-caption"><strong>{html(caption)}</strong></figcaption></figure>')
    return "\n".join(figures)


def pagination(current: int, total: int, style: str) -> str:
    if total <= 1:
        return ""

    def link(number: int, label: str, classes: str) -> str:
        # The first page and all derived pages share the index page's base URL.
        target = f"page/{number}/" if number > 1 else "./"
        return f'<a class="{classes}" href="{target}">{label}</a>'

    advanced = style == "advanced"
    wrapper = "pods-pagination-advanced" if advanced else "pods-pagination-paginate"
    chunks = [f'<p class="pods-pagination"><span class="{wrapper}">']
    if current > 1:
        if advanced:
            chunks.append(link(1, "« First", "pods-pagination-label pods-pagination-first"))
        prev_class = "pods-pagination-label pods-pagination-prev" if advanced else "prev page-numbers"
        chunks.append(link(current - 1, "‹ Previous", prev_class))
    shown = {1, total} | set(range(max(1, current - 2), min(total + 1, current + 3)))
    previous = 0
    for number in sorted(shown):
        if number > previous + 1 and not advanced:
            chunks.append('<span class="page-numbers dots">…</span>')
        if number == current:
            cls = "pods-pagination-number pods-pagination-current" if advanced else "page-numbers current"
            chunks.append(f'<span aria-current="page" class="{cls}">{number}</span>')
        else:
            cls = f"pods-pagination-number pods-pagination-{number}" if advanced else "page-numbers"
            chunks.append(link(number, str(number), cls))
        previous = number
    if current < total:
        next_class = "pods-pagination-label pods-pagination-next" if advanced else "next page-numbers"
        chunks.append(link(current + 1, "Next ›", next_class))
        if advanced:
            chunks.append(link(total, "Last »", "pods-pagination-label pods-pagination-last"))
    chunks.append("</span></p>")
    return "\n".join(chunks)


def selected_for_view(papers: list[dict], view: dict) -> list[dict]:
    if profile := view.get("profile"):
        return [paper for paper in papers if profile in paper.get("profiles", [])]
    return papers


def archive_page(template: str, page: int, total: int) -> str:
    template = PAGE_COUNT.sub("", template)
    if page == 1:
        return template.replace("</head>", f'<meta name="mlps-publication-pages" content="{total}">\n</head>', 1)
    # Regular index.html pages can use relative links even on a project Pages
    # site. Keep their base for styles, navigation and media on deeper pages.
    template, n = re.subn(r"<head\b[^>]*>", lambda match: f'{match[0]}\n<base href="../../">\n{GENERATED}',
                          template, count=1, flags=re.I)
    if n != 1:
        raise ValueError("Missing <head> in publication template")
    template = re.sub(r'''(\bhref\s*=\s*["'])#''', lambda match: f"{match[1]}page/{page}/#", template,
                      flags=re.I)
    # A canonical for a profile's first page must not cover all subsequent
    # archive pages; those pages have their own stable static URLs.
    def canonical(match: re.Match) -> str:
        prefix, url, suffix = match.groups()
        return f"{prefix}{url.rstrip('/')}/page/{page}/{suffix}"

    return re.sub(r'''(<link\b[^>]*\brel=["']canonical["'][^>]*\bhref=["'])([^"']+)(["'][^>]*>)''',
                  canonical, template, flags=re.I)


def read_papers(directory: Path) -> list[dict]:
    papers = []
    for path in sorted(directory.glob("*.toml")):
        try:
            with path.open("rb") as file:
                paper = tomllib.load(file)
            if not isinstance(paper.get("title"), str) or not paper["title"].strip():
                raise ValueError("title is required")
            if "authors" in paper and (not isinstance(paper["authors"], list)
                                        or not all(isinstance(a, str) for a in paper["authors"])):
                raise ValueError("authors must be an array of names")
            stamp = str(paper.get("date", ""))
            if not re.fullmatch(r"\d{4}", stamp):
                date.fromisoformat(stamp)
                if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", stamp):
                    raise ValueError("date must be YYYY-MM-DD or YYYY")
            paper["date"] = stamp
            if not isinstance(paper.get("profiles", []), list):
                raise ValueError("profiles must be an array of profile identifiers")
            paper["id"] = path.stem
            papers.append(paper)
        except (tomllib.TOMLDecodeError, ValueError) as error:
            raise ValueError(f"{path.name}: {error}") from error
    # Match the original Pods query: full publication date descending, then
    # case- and accent-insensitive title ascending within that date.
    def title_order(paper: dict) -> str:
        letters = unicodedata.normalize("NFKD", paper["title"]).casefold()
        return "".join(c for c in letters if not unicodedata.combining(c))
    papers.sort(key=title_order)
    papers.sort(key=lambda paper: paper["date"], reverse=True)
    return papers


def write_site(site: Path, papers: list[dict], views: dict) -> tuple[int, int]:
    output = {}
    stale = []
    known = {view.get("profile") for view in views.values()}
    for paper in papers:
        if unknown := set(paper.get("profiles", [])) - known:
            raise ValueError(f"Unknown profiles in {paper['id']}: {sorted(unknown)}")
    for route, view in views.items():
        if not re.fullmatch(r"/(?:[\w-]+/)+", route):
            raise ValueError(f"Invalid view route: {route}")
        directory = site / route.strip("/")
        first = directory / "index.html"
        template = first.read_text(encoding="utf-8")
        if HIGHLIGHTS[0] in template:
            template = marked_section(template, HIGHLIGHTS, highlights(papers, route))
        selection = selected_for_view(papers, view)
        size = view["per_page"]
        if not isinstance(size, int) or size < 1:
            raise ValueError(f"Invalid per_page in {route}")
        total = max(1, math.ceil(len(selection) / size))
        for page in range(1, total + 1):
            nav = pagination(page, total, view.get("pagination", "default"))
            rows = selection[(page - 1) * size:page * size]
            content = "\n".join([nav if view.get("top_pager") else "",
                                 *(card(paper, route) for paper in rows), nav])
            document = archive_page(marked_section(template, PUBLICATIONS, content), page, total)
            dest = first if page == 1 else directory / "page" / str(page) / "index.html"
            output[dest] = document
        # Removed entries may previously have filled another generated page.
        # Preserve any independently maintained files in the same directory.
        for previous in (directory / "page").glob("*/index.html"):
            number = previous.parent.name
            if number.isdecimal() and int(number) > total and GENERATED in previous.read_text(encoding="utf-8"):
                stale.append(previous)
    # Finish validating all templates and data before changing any output.
    for dest, document in output.items():
        if dest.exists() and dest.read_text(encoding="utf-8") == document:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        with NamedTemporaryFile(mode="w", encoding="utf-8", dir=dest.parent, delete=False) as temp:
            temp.write(document)
        Path(temp.name).chmod(0o644)
        Path(temp.name).replace(dest)
    for previous in stale:
        previous.unlink(missing_ok=True)
        if previous.parent.exists() and not any(previous.parent.iterdir()):
            previous.parent.rmdir()
    return len(views), len(output)


def main() -> None:
    papers = read_papers(ROOT / "data/publications")
    views = json.loads((ROOT / "data/publication-views.json").read_text(encoding="utf-8"))
    n_views, n_pages = write_site(ROOT / "docs", papers, views)
    print(f"{len(papers)} publications, {n_views} views, {n_pages} HTML pages")


if __name__ == "__main__":
    main()
